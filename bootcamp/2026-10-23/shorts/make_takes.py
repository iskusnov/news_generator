def end_of(phrase, a, b):
    ks = [re.sub(r'[^\wё-]', '', k.lower()) for k in phrase.split()]
    for i, w in enumerate(W):
        if a <= w['start'] <= b and all(i + j < len(N) and N[i + j].startswith(k) for j, k in enumerate(ks)):
            j = i + len(ks) - 1; nxt = W[j + 1]['start'] if j + 1 < len(W) else W[j]['end'] + 1
            return round(min(W[j]['end'] + .08, nxt - .02), 2)
    raise SystemExit(f'END NOT FOUND {phrase!r} {a}-{b}')

def seg(sp, a, ep, b):
    return {'in': round(find(sp, a - 3, a + 6) - .05, 2), 'out': end_of(ep, b - 6, b + 4), 'tag': 'main'}

