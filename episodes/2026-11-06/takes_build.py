def snap(a, b):
    ws = [w for w in W if w['start'] >= a - 0.06 and w['start'] < b and not w['word'].lower().strip('.!,…').startswith('стоп')]
    while ws and ws[-1]['word'].lower().strip('.!,') in ('стоп', 'продолжение', 'следует...'): ws.pop()
    i = W.index(ws[-1]); end = ws[-1]['end']
    if i + 1 < len(W): end = min(end, max(ws[-1]['start'] + 0.6, W[i + 1]['start'] - 0.05))
    end = min(end, ws[-1]['start'] + max(1.4, 0.09 * len(ws[-1]['word'])))  # Whisper растягивает последнее слово на паузу/следующий заход
    return round(ws[0]['start'], 2), round(end, 2)
